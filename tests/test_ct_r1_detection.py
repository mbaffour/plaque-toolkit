#  D2: the app dish comes from the standard pass
# --------------------------------------------------------------------------- #
@pytest.mark.parametrize("name,mm,old_px,new_px", [
    ("large/Plate_8", 90, 1177.3, 1121.97),       # the halo dish was +4.9 %
    ("small/Plate_11", 55, 1173.58, 1123.82),     # +4.4 %
])
def test_d2_dish_from_standard_pass(name, mm, old_px, new_px):
    from app import engine_api
    path = _plate_path(name)
    for scale in ("auto", "small", "standard"):
        d = engine_api.detect_single(path, plate_mm=mm, scale=scale)
        assert round(d["plate"]["diam_px"], 2) == new_px, scale
        assert d["dish_source"] == "standard pass"
    # the old one-pass -small path (what Precise still uses) keeps the halo dish
    legacy = engine_api.detect_single(path, plate_mm=mm, small=True, legacy=True)
    assert round(legacy["plate"]["diam_px"], 2) == old_px


def test_d2_plate2_gets_a_dish_in_small_mode():
    from app import engine_api
    path = _plate_path("large/Plate_2")
    legacy = engine_api.detect_single(path, plate_mm=90, small=True, legacy=True)
    assert legacy["plate"] is None and not legacy["pxl_per_mm"]
    d = engine_api.detect_single(path, plate_mm=90, scale="small")
    assert round(d["plate"]["diam_px"], 2) == 2116.81 and d["pxl_per_mm"]


def test_d2_no_dish_carries_a_reason(tmp_path):
    import cv2
    from app import engine_api
    img = np.full((600, 600, 3), 150, np.uint8)
    cv2.circle(img, (300, 300), 20, (70, 70, 70), -1)
