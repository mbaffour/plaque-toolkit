def test_d1_auto_contains_every_standard_plaque_on_a_bundled_plate():
    """Plate_8: every standard-pass plaque is in Auto with exactly its standard area and
    centre (so exactly its standard diameter); Auto adds the small-pass extras on top."""
    from app import engine_api
    path = _plate_path("large/Plate_8")
    std = engine_api.detect_single(path, plate_mm=90, scale="standard")
    auto = engine_api.detect_single(path, plate_mm=90, scale="auto")
    key = lambda p: (p["area_pxl"], round(p["center"][0], 6), round(p["center"][1], 6))
    auto_keys = {key(p) for p in auto["plaques"] if p["source"] == "auto"}
    assert {key(p) for p in std["plaques"]} == auto_keys
    assert std["pxl_per_mm"] == auto["pxl_per_mm"]
    assert std["n_plaques"] == 19 and auto["n_plaques"] == 27
    assert sum(p["source"] == "small" for p in auto["plaques"]) == 8
    meds = [float(np.median([2 * math.sqrt(p["area_pxl"] / math.pi) * d["pxl_per_mm"]
                             for p in d["plaques"] if p["source"] == "auto"]))
            for d in (std, auto)]
    assert meds[0] == meds[1] and round(meds[0], 2) == 5.57


def test_d1_containment_dedup_drops_concentric_core():
    import numpy as np
    import plaque_gui as pgui

    def disc(cx, cy, r):
        t = np.linspace(0, 2 * np.pi, 40, endpoint=False)
        pts = np.stack([cx + r * np.cos(t), cy + r * np.sin(t)], 1).astype(np.int32)
        return {"source": "auto", "kind": "contour", "contour": pts,
                "area_pxl": math.pi * r * r, "center": (cx, cy)}
    halo, core, other = disc(100, 100, 30), disc(108, 100, 12), disc(300, 100, 12)
    kept, n = pgui.dedupe_by_containment([core, other, halo])
    assert n == 1 and kept == [other, halo]
    merged, n_add = pgui.merge_scales([halo], [core, other])
    assert n_add == 1 and merged[1] is other and other["source"] == "small"


