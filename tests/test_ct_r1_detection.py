with open(PIN) as _fh:
    _PIN = json.load(_fh)["plates"]


@pytest.mark.parametrize("name", sorted(_PIN))
@pytest.mark.parametrize("mode", ["pub", "pub_small"])
def test_published_app_path_unchanged(name, mode):
    from app import engine_api
    exp = _PIN[name][mode]
    det = engine_api.detect_single(_plate_path(name), plate_mm=_PIN[name]["plate_mm"],
                                   published=True, small=(mode == "pub_small"))
    got = sorted([round(p["area_pxl"], 2), round(p["center"][0], 2), round(p["center"][1], 2)]
                 for p in det["plaques"])
    assert det["n_plaques"] == exp["n"]
    assert got == exp["plaques"]
    assert (round(det["plate"]["diam_px"], 2) if det["plate"] else None) == exp["dish_px"]
    assert det["pxl_per_mm"] == exp["ppm"]
    assert all(p["source"] == "auto" for p in det["plaques"])
