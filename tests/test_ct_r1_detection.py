def test_d1_auto_keeps_standard_outline_and_adds_small_discs(mixed_plate):
    from app import engine_api
    std = engine_api.detect_single(mixed_plate, plate_mm=90, scale="standard")
    sml = engine_api.detect_single(mixed_plate, plate_mm=90, scale="small")
    auto = engine_api.detect_single(mixed_plate, plate_mm=90, scale="auto")
    assert std["scale"] == "standard" and sml["scale"] == "small" and auto["scale"] == "auto"
    # the standard pass finds only the big disc, at (about) its true area pi*60^2 = 11310 px
    assert std["n_plaques"] == 1
    big_std = std["plaques"][0]
    assert _near(big_std, BIG_C)
    assert abs(big_std["area_pxl"] - math.pi * BIG_R ** 2) / (math.pi * BIG_R ** 2) < 0.06
    # the small pass outlines only the core of the big disc: about half the area (F1)
    big_sml = [p for p in sml["plaques"] if _near(p, BIG_C)]
    assert len(big_sml) == 1 and big_sml[0]["area_pxl"] < 0.6 * big_std["area_pxl"]
    # Auto: the big disc with EXACTLY its standard outline, plus the five 1 mm discs
    assert auto["n_plaques"] == 6 and auto["n_small_added"] == 5
    big_auto = [p for p in auto["plaques"] if _near(p, BIG_C)]
    assert len(big_auto) == 1
    assert big_auto[0]["area_pxl"] == big_std["area_pxl"]
    assert big_auto[0]["source"] == "auto"
    for c in SMALL_CS:
        hit = [p for p in auto["plaques"] if _near(p, c)]
        assert len(hit) == 1 and hit[0]["source"] == "small"
    # the same calibration in all three (the dish comes from the standard pass)
    assert std["pxl_per_mm"] == sml["pxl_per_mm"] == auto["pxl_per_mm"]
    # and so the same diameter in mm for the big disc
    from plaque_gui import measure
    assert measure(big_auto[0]["area_pxl"], auto["pxl_per_mm"], False) == \
        measure(big_std["area_pxl"], std["pxl_per_mm"], False)


